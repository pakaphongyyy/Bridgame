// กำหนดว่าไฟล์นี้อยู่ในแพ็กเกจ `birdgame` เพื่อจัดโครงสร้างคลาสให้เป็นหมวดหมู่
package birdgame;

// นำเข้า AppFont เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import birdgame.ui.AppFont;
// นำเข้า StartFrame เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import birdgame.ui.StartFrame;

// นำเข้า SwingUtilities เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import javax.swing.SwingUtilities;
//import javax.swing.UIManager;

// ประกาศคลาส `Main` ซึ่งเป็นหน่วยหลักที่รวมข้อมูล (fields) และพฤติกรรม (methods) ของส่วนนี้
public class Main {
    // เมธอด main() คือจุดที่ JVM เรียกเป็นอันดับแรกเมื่อเริ่มโปรแกรม
    public static void main(String[] args) {
        // ใช้ฟอนต์ที่รองรับภาษาไทยทั้งโปรแกรม
        // เรียก `AppFont.applyToSwing(...)` เพื่อให้ขั้นตอนย่อยนี้ทำงาน
        AppFont.applyToSwing();

        SwingUtilities.invokeLater(() -> {
            // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `StartFrame frame` เพื่อใช้ต่อในขั้นตอนถัดไป
            StartFrame frame = new StartFrame();
            // ทำให้หน้าต่างหรือ component นี้แสดงบนหน้าจอ
            frame.setVisible(true);
        });
    }
}
