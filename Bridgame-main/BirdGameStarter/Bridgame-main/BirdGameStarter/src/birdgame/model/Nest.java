// กำหนดว่าไฟล์นี้อยู่ในแพ็กเกจ `birdgame.model` เพื่อจัดโครงสร้างคลาสให้เป็นหมวดหมู่
package birdgame.model;

// นำเข้า Color เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import java.awt.Color;
// นำเข้า Graphics เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import java.awt.Graphics;
// นำเข้า Rectangle เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import java.awt.Rectangle;

// ประกาศคลาส `Nest` ซึ่งเป็นหน่วยหลักที่รวมข้อมูล (fields) และพฤติกรรม (methods) ของส่วนนี้
public class Nest {
    // ประกาศค่าคงที่ `WIDTH` ใช้ร่วมกันในคลาส และไม่ควรถูกเปลี่ยนค่าหลังประกาศ
    public static final int WIDTH = 90;
    // ประกาศค่าคงที่ `HEIGHT` ใช้ร่วมกันในคลาส และไม่ควรถูกเปลี่ยนค่าหลังประกาศ
    public static final int HEIGHT = 50;

    // ประกาศ field `x` เพื่อเก็บสถานะที่คลาสนี้ต้องใช้ระหว่างการทำงาน
    private int x;
    // ประกาศ field `y` แบบ final หมายถึงหลังสร้างอ็อบเจ็กต์แล้วจะไม่เปลี่ยนการอ้างอิง field นี้
    private final int y;
    // ประกาศ field `speed` แบบ final หมายถึงหลังสร้างอ็อบเจ็กต์แล้วจะไม่เปลี่ยนการอ้างอิง field นี้
    private final int speed;
    // ประกาศ field `stopX` แบบ final หมายถึงหลังสร้างอ็อบเจ็กต์แล้วจะไม่เปลี่ยนการอ้างอิง field นี้
    private final int stopX;   // รังหยุดเลื่อนเมื่อถึงตำแหน่งนี้

    /** รังเกิดที่ขอบขวา วางบนพื้น แล้วเลื่อนเข้ามาจนถึง stopX */
    // Constructor ของ `Nest` ทำงานเมื่อสร้างอ็อบเจ็กต์ใหม่ ใช้กำหนดค่าเริ่มต้นและเตรียมส่วนที่จำเป็น
    public Nest(int panelWidth, int panelHeight, int groundHeight, int speed, int stopX) {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.x` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.x = panelWidth;
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.y` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.y = panelHeight - groundHeight - HEIGHT;
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.speed` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.speed = speed;
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.stopX` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.stopX = stopX;
    }

    // อัปเดตสถานะของอ็อบเจ็กต์หนึ่งเฟรม เช่น ตำแหน่ง/ความเร็ว/Animation
    public void update() {
        // ตรวจเงื่อนไข `x > stopX`; ถ้าเป็นจริงจึงทำคำสั่งภายในบล็อกถัดไป
        if (x > stopX) {
            // ใช้ฟังก์ชันคณิตศาสตร์ของ Java เพื่อคำนวณค่าที่ใช้กับตำแหน่ง/Animation
            x = Math.max(stopX, x - speed);
        }
    }

    // คืน Rectangle ที่ใช้เป็น hitbox สำหรับตรวจ Collision
    public Rectangle getBounds() {
        // ส่งค่า `new Rectangle(x, y, WIDTH, HEIGHT)` กลับไปยังผู้เรียกเมธอด แล้วจบการทำงานของเมธอดนี้
        return new Rectangle(x, y, WIDTH, HEIGHT);
    }

    // ประกาศค่าคงที่ `DRAW_WIDTH` ใช้ร่วมกันในคลาส และไม่ควรถูกเปลี่ยนค่าหลังประกาศ
    private static final int DRAW_WIDTH = 126;   // ภาพกว้างกว่า hitbox (กิ่งไม้ยื่นออก)
    // ประกาศค่าคงที่ `DRAW_HEIGHT` ใช้ร่วมกันในคลาส และไม่ควรถูกเปลี่ยนค่าหลังประกาศ
    private static final int DRAW_HEIGHT = 70;

    // วาดอ็อบเจ็กต์ลงบน Graphics ของ Swing
    public void draw(Graphics g) {
        // ตรวจเงื่อนไข `Sprites.NEST != null`; ถ้าเป็นจริงจึงทำคำสั่งภายในบล็อกถัดไป
        if (Sprites.NEST != null) {
            // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int drawX` เพื่อใช้ต่อในขั้นตอนถัดไป
            int drawX = x + WIDTH / 2 - DRAW_WIDTH / 2;
            // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int drawY` เพื่อใช้ต่อในขั้นตอนถัดไป
            int drawY = y + HEIGHT - DRAW_HEIGHT + 6;   // ก้นรังจมพื้นนิดหน่อย
            // วาดรูปภาพลงบนหน้าจอตามตำแหน่งและขนาดที่กำหนด
            g.drawImage(Sprites.NEST, drawX, drawY, DRAW_WIDTH, DRAW_HEIGHT, null);
            // ออกจากเมธอดทันทีโดยไม่คืนค่า ใช้หยุดการทำงานส่วนที่เหลือของเมธอด
            return;
        }

        // กำหนดสีที่จะใช้วาดคำสั่งกราฟิกถัดไป
        g.setColor(new Color(139, 90, 43));          // ไม่มีภาพ → วงรีน้ำตาล
        // วาดวงรีทึบ ใช้ประกอบฉาก เช่น เมฆ ดวงอาทิตย์ หรือกราฟิกสำรอง
        g.fillOval(x, y, WIDTH, HEIGHT);
        // กำหนดสีที่จะใช้วาดคำสั่งกราฟิกถัดไป
        g.setColor(new Color(100, 60, 25));
        // เรียก `g.drawOval(...)` เพื่อให้ขั้นตอนย่อยนี้ทำงาน
        g.drawOval(x, y, WIDTH, HEIGHT);
    }

    // Getter `getX()` คืนค่าข้อมูลภายในคลาสให้ส่วนอื่นอ่านได้โดยไม่เข้าถึง field โดยตรง
    public int getX() { return x; }
    // Getter `getY()` คืนค่าข้อมูลภายในคลาสให้ส่วนอื่นอ่านได้โดยไม่เข้าถึง field โดยตรง
    public int getY() { return y; }
}
