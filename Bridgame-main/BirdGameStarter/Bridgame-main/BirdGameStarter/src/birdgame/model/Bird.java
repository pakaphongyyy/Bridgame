// กำหนดว่าไฟล์นี้อยู่ในแพ็กเกจ `birdgame.model` เพื่อจัดโครงสร้างคลาสให้เป็นหมวดหมู่
package birdgame.model;
// นำเข้า Graphics เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import java.awt.Graphics;

// ประกาศคลาส `Bird` ซึ่งเป็นหน่วยหลักที่รวมข้อมูล (fields) และพฤติกรรม (methods) ของส่วนนี้
public class Bird {

    // ประกาศ field `x` เพื่อเก็บสถานะที่คลาสนี้ต้องใช้ระหว่างการทำงาน
    private int x;
    // ประกาศ field `y` เพื่อเก็บสถานะที่คลาสนี้ต้องใช้ระหว่างการทำงาน
    private int y;

    // ความเร็วขึ้นลงของนก
    // ประกาศ field `velocityY` เพื่อเก็บสถานะที่คลาสนี้ต้องใช้ระหว่างการทำงาน
    private double velocityY;

    
    // ประกาศ field `alive` เพื่อเก็บสถานะที่คลาสนี้ต้องใช้ระหว่างการทำงาน
    private boolean alive = true;
    // ประกาศ field `flyingToNest` เพื่อเก็บสถานะที่คลาสนี้ต้องใช้ระหว่างการทำงาน
    private boolean flyingToNest = false;
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `private int animationTick` เพื่อใช้ต่อในขั้นตอนถัดไป
    private int animationTick = 0;  //เก็บเฟรมนก
    // ประกาศ field `animationFrame` เพื่อเก็บสถานะที่คลาสนี้ต้องใช้ระหว่างการทำงาน
    private int animationFrame = 0;

    // Constructor ของ `Bird` ทำงานเมื่อสร้างอ็อบเจ็กต์ใหม่ ใช้กำหนดค่าเริ่มต้นและเตรียมส่วนที่จำเป็น
    public Bird(int x, int y) {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.x` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.x = x;
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.y` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.y = y;
    }

    // กด Space = นกบินขึ้น
    // ทำให้นกพุ่งขึ้นโดยเปลี่ยนความเร็วแนวตั้งเป็นค่าติดลบ
    public void jump() {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `velocityY` เพื่อใช้ต่อในขั้นตอนถัดไป
        velocityY = -7.5;
    }

    // รีเซตสถานะนกกลับไปตำแหน่งและค่าตั้งต้น
    public void reset() {
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `x` เพื่อใช้ต่อในขั้นตอนถัดไป
    x = 120;
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `y` เพื่อใช้ต่อในขั้นตอนถัดไป
    y = 200;
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `velocityY` เพื่อใช้ต่อในขั้นตอนถัดไป
    velocityY = 0;
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `alive` เพื่อใช้ต่อในขั้นตอนถัดไป
    alive = true;
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `flyingToNest` เพื่อใช้ต่อในขั้นตอนถัดไป
    flyingToNest = false;
}
    // อัปเดตสถานะของอ็อบเจ็กต์หนึ่งเฟรม เช่น ตำแหน่ง/ความเร็ว/Animation
    public void update() {
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `velocityY +` เพื่อใช้ต่อในขั้นตอนถัดไป
    velocityY += 0.45;
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `y +` เพื่อใช้ต่อในขั้นตอนถัดไป
    y += (int) velocityY;

    // Animation นกกะพือปีก3เฟรม
    // คำสั่งนี้เปลี่ยน/กำหนดสถานะบางอย่างของโปรแกรมตามค่าที่ระบุ
    animationTick++;

    // ตรวจเงื่อนไข `animationTick >= 6`; ถ้าเป็นจริงจึงทำคำสั่งภายในบล็อกถัดไป
    if (animationTick >= 6) {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `animationTick` เพื่อใช้ต่อในขั้นตอนถัดไป
        animationTick = 0;
        // คำสั่งนี้เปลี่ยน/กำหนดสถานะบางอย่างของโปรแกรมตามค่าที่ระบุ
        animationFrame++;

        // ตรวจเงื่อนไข `animationFrame >= 3`; ถ้าเป็นจริงจึงทำคำสั่งภายในบล็อกถัดไป
        if (animationFrame >= 3) {
            // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `animationFrame` เพื่อใช้ต่อในขั้นตอนถัดไป
            animationFrame = 0;
        }
    }
}

    // วาดอ็อบเจ็กต์ลงบน Graphics ของ Swing
    public void draw(Graphics g) {

    // ตรวจเงื่อนไข `Sprites.BIRD == null`; ถ้าเป็นจริงจึงทำคำสั่งภายในบล็อกถัดไป
    if (Sprites.BIRD == null) {
        // ออกจากเมธอดทันทีโดยไม่คืนค่า ใช้หยุดการทำงานส่วนที่เหลือของเมธอด
        return;
    }
       //ตัดรูป 
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int[] frameX` เพื่อใช้ต่อในขั้นตอนถัดไป
    int[] frameX = {81, 480, 1028};
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int[] frameWidth` เพื่อใช้ต่อในขั้นตอนถัดไป
    int[] frameWidth = {312, 462, 313};

    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int sx` เพื่อใช้ต่อในขั้นตอนถัดไป
    int sx = frameX[animationFrame];
    // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int sw` เพื่อใช้ต่อในขั้นตอนถัดไป
    int sw = frameWidth[animationFrame];

    // วาดรูปภาพลงบนหน้าจอตามตำแหน่งและขนาดที่กำหนด
    g.drawImage(
            Sprites.BIRD,
            x,
            y,
            x + 55,
            y + 55,
            sx,
            0,
            sx + sw,
            Sprites.BIRD.getHeight(),
            null
    );
}

    // เรียกการอัปเดตการตกของนก โดยใช้ logic เดียวกับ update()
    public void fall() {
        // เรียก `update(...)` เพื่อให้ขั้นตอนย่อยนี้ทำงาน
        update();
    }

    // ตั้งสถานะให้นกเข้าสู่ช่วงบินไปหารัง
    public void flyToNest() {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `flyingToNest` เพื่อใช้ต่อในขั้นตอนถัดไป
        flyingToNest = true;
    }

    // Getter `getX()` คืนค่าข้อมูลภายในคลาสให้ส่วนอื่นอ่านได้โดยไม่เข้าถึง field โดยตรง
    public int getX() {
        // ส่งค่า `x` กลับไปยังผู้เรียกเมธอด แล้วจบการทำงานของเมธอดนี้
        return x;
    }

    // Getter `getY()` คืนค่าข้อมูลภายในคลาสให้ส่วนอื่นอ่านได้โดยไม่เข้าถึง field โดยตรง
    public int getY() {
        // ส่งค่า `y` กลับไปยังผู้เรียกเมธอด แล้วจบการทำงานของเมธอดนี้
        return y;
    }

    // Getter `getVelocityY()` คืนค่าข้อมูลภายในคลาสให้ส่วนอื่นอ่านได้โดยไม่เข้าถึง field โดยตรง
    public double getVelocityY() {
        // ส่งค่า `velocityY` กลับไปยังผู้เรียกเมธอด แล้วจบการทำงานของเมธอดนี้
        return velocityY;
    }

    // เมธอด `isAlive()` คืนค่า boolean เพื่อบอกว่าสถานะตามชื่อเมธอดเป็นจริงหรือไม่
    public boolean isAlive() {
        // ส่งค่า `alive` กลับไปยังผู้เรียกเมธอด แล้วจบการทำงานของเมธอดนี้
        return alive;
    }

    // เมธอด `isFlyingToNest()` คืนค่า boolean เพื่อบอกว่าสถานะตามชื่อเมธอดเป็นจริงหรือไม่
    public boolean isFlyingToNest() {
        // ส่งค่า `flyingToNest` กลับไปยังผู้เรียกเมธอด แล้วจบการทำงานของเมธอดนี้
        return flyingToNest;
    }

    // Setter `setAlive()` ใช้เปลี่ยนค่าภายในอ็อบเจ็กต์อย่างเป็นทางการ
    public void setAlive(boolean alive) {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.alive` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.alive = alive;
    }

    // Setter `setPosition()` ใช้เปลี่ยนค่าภายในอ็อบเจ็กต์อย่างเป็นทางการ
    public void setPosition(int x, int y) {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.x` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.x = x;
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.y` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.y = y;
    }
}
