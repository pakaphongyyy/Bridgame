// กำหนดว่าไฟล์นี้อยู่ในแพ็กเกจ `birdgame.model` เพื่อจัดโครงสร้างคลาสให้เป็นหมวดหมู่
package birdgame.model;

// นำเข้า Color เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import java.awt.Color;
// นำเข้า Graphics เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import java.awt.Graphics;
// นำเข้า Rectangle เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import java.awt.Rectangle;
// นำเข้า Random เพื่อให้ไฟล์นี้เรียกใช้คลาสดังกล่าวได้โดยไม่ต้องเขียนชื่อแพ็กเกจเต็ม
import java.util.Random;

// ประกาศคลาส `Heart` ซึ่งเป็นหน่วยหลักที่รวมข้อมูล (fields) และพฤติกรรม (methods) ของส่วนนี้
public class Heart {
    // ประกาศค่าคงที่ `SIZE` ใช้ร่วมกันในคลาส และไม่ควรถูกเปลี่ยนค่าหลังประกาศ
    public static final int SIZE = 30;
    // ประกาศค่าคงที่ `RANDOM` ใช้ร่วมกันในคลาส และไม่ควรถูกเปลี่ยนค่าหลังประกาศ
    private static final Random RANDOM = new Random();

    // ประกาศ field `x` เพื่อเก็บสถานะที่คลาสนี้ต้องใช้ระหว่างการทำงาน
    private int x;
    // ประกาศ field `y` แบบ final หมายถึงหลังสร้างอ็อบเจ็กต์แล้วจะไม่เปลี่ยนการอ้างอิง field นี้
    private final int y;
    // ประกาศ field `speed` แบบ final หมายถึงหลังสร้างอ็อบเจ็กต์แล้วจะไม่เปลี่ยนการอ้างอิง field นี้
    private final int speed;
    // ประกาศ field `collected` เพื่อเก็บสถานะที่คลาสนี้ต้องใช้ระหว่างการทำงาน
    private boolean collected;

    // Constructor ของ `Heart` ทำงานเมื่อสร้างอ็อบเจ็กต์ใหม่ ใช้กำหนดค่าเริ่มต้นและเตรียมส่วนที่จำเป็น
    public Heart(int x, int y, int speed) {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.x` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.x = x;
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.y` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.y = y;
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `this.speed` เพื่อใช้ต่อในขั้นตอนถัดไป
        this.speed = speed;
    }

    /** วางหัวใจกลางช่องว่างของท่อ (เก็บได้ถ้าบินผ่านตรงกลาง) */
    // สร้างหัวใจให้อยู่กึ่งกลางช่องว่างระหว่างท่อบนกับท่อล่าง
    public static Heart spawnInGap(Pipe pipe, int speed) {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int hx` เพื่อใช้ต่อในขั้นตอนถัดไป
        int hx = pipe.getX() + Pipe.WIDTH / 2 - SIZE / 2;
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int hy` เพื่อใช้ต่อในขั้นตอนถัดไป
        int hy = pipe.getGapY() + pipe.getGap() / 2 - SIZE / 2;
        // ส่งค่า `new Heart(hx, hy, speed)` กลับไปยังผู้เรียกเมธอด แล้วจบการทำงานของเมธอดนี้
        return new Heart(hx, hy, speed);
    }

    /** วางหัวใจที่ขอบขวาจอ สุ่มความสูง (ใช้ spawn ระหว่างท่อ) */
    // สร้างหัวใจที่ตำแหน่งความสูงแบบสุ่ม
    public static Heart spawnRandom(int panelWidth, int panelHeight, int groundHeight, int speed) {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int minY` เพื่อใช้ต่อในขั้นตอนถัดไป
        int minY = 40;
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int maxY` เพื่อใช้ต่อในขั้นตอนถัดไป
        int maxY = panelHeight - groundHeight - SIZE - 40;
        // ใช้ฟังก์ชันคณิตศาสตร์ของ Java เพื่อคำนวณค่าที่ใช้กับตำแหน่ง/Animation
        int hy = minY + RANDOM.nextInt(Math.max(1, maxY - minY + 1));
        // ส่งค่า `new Heart(panelWidth, hy, speed)` กลับไปยังผู้เรียกเมธอด แล้วจบการทำงานของเมธอดนี้
        return new Heart(panelWidth, hy, speed);
    }

    // อัปเดตสถานะของอ็อบเจ็กต์หนึ่งเฟรม เช่น ตำแหน่ง/ความเร็ว/Animation
    public void update() {
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `x -` เพื่อใช้ต่อในขั้นตอนถัดไป
        x -= speed;
    }

    // ตรวจว่าวัตถุเลื่อนออกนอกขอบซ้ายของหน้าจอแล้วหรือยัง
    public boolean isOffScreen() {
        // ส่งค่า `x + SIZE < 0` กลับไปยังผู้เรียกเมธอด แล้วจบการทำงานของเมธอดนี้
        return x + SIZE < 0;
    }

    // คืน Rectangle ที่ใช้เป็น hitbox สำหรับตรวจ Collision
    public Rectangle getBounds() {
        // ส่งค่า `new Rectangle(x, y, SIZE, SIZE)` กลับไปยังผู้เรียกเมธอด แล้วจบการทำงานของเมธอดนี้
        return new Rectangle(x, y, SIZE, SIZE);
    }

    // ทำเครื่องหมายว่าหัวใจนี้ถูกเก็บแล้ว
    public void collect() { collected = true; }
    // เมธอด `isCollected()` คืนค่า boolean เพื่อบอกว่าสถานะตามชื่อเมธอดเป็นจริงหรือไม่
    public boolean isCollected() { return collected; }

    // ประกาศค่าคงที่ `DRAW_SIZE` ใช้ร่วมกันในคลาส และไม่ควรถูกเปลี่ยนค่าหลังประกาศ
    private static final int DRAW_SIZE = 40;   // ภาพใหญ่กว่า hitbox 30 นิดหน่อย ให้เห็นชัด

    // วาดอ็อบเจ็กต์ลงบน Graphics ของ Swing
    public void draw(Graphics g) {
        // ตรวจเงื่อนไข `collected`; ถ้าเป็นจริงจึงทำคำสั่งภายในบล็อกถัดไป
        if (collected) return;

        // ตรวจเงื่อนไข `Sprites.HEART != null`; ถ้าเป็นจริงจึงทำคำสั่งภายในบล็อกถัดไป
        if (Sprites.HEART != null) {
            // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int off` เพื่อใช้ต่อในขั้นตอนถัดไป
            int off = (DRAW_SIZE - SIZE) / 2;
            // วาดรูปภาพลงบนหน้าจอตามตำแหน่งและขนาดที่กำหนด
            g.drawImage(Sprites.HEART, x - off, y - off, DRAW_SIZE, DRAW_SIZE, null);
            // ออกจากเมธอดทันทีโดยไม่คืนค่า ใช้หยุดการทำงานส่วนที่เหลือของเมธอด
            return;
        }

        // กำหนดสีที่จะใช้วาดคำสั่งกราฟิกถัดไป
        g.setColor(Color.RED);                     // ไม่มีภาพ → หัวใจวาดเอง
        // คำนวณหรือสร้างค่าทางขวา แล้วเก็บผลไว้ใน `int half` เพื่อใช้ต่อในขั้นตอนถัดไป
        int half = SIZE / 2;
        // วาดวงรีทึบ ใช้ประกอบฉาก เช่น เมฆ ดวงอาทิตย์ หรือกราฟิกสำรอง
        g.fillOval(x, y, half + 2, half + 2);
        // วาดวงรีทึบ ใช้ประกอบฉาก เช่น เมฆ ดวงอาทิตย์ หรือกราฟิกสำรอง
        g.fillOval(x + half - 2, y, half + 2, half + 2);
        g.fillPolygon(new int[]{x, x + SIZE, x + half},
                      // คำสั่งนี้เปลี่ยน/กำหนดสถานะบางอย่างของโปรแกรมตามค่าที่ระบุ
                      new int[]{y + half / 2 + 3, y + half / 2 + 3, y + SIZE}, 3);
    }

    // Getter `getX()` คืนค่าข้อมูลภายในคลาสให้ส่วนอื่นอ่านได้โดยไม่เข้าถึง field โดยตรง
    public int getX() { return x; }
    // Getter `getY()` คืนค่าข้อมูลภายในคลาสให้ส่วนอื่นอ่านได้โดยไม่เข้าถึง field โดยตรง
    public int getY() { return y; }
}
